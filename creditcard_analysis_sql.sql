   ============================================================ */


/* Q11. Top 3 Customers Within Each Profession

   Find the highest-revenue customers in each profession.
*/

WITH customer_revenue AS (
    SELECT
        cd.Customer_Job,
        cc.Client_Num,
        SUM(cc.Total_Trans_Amt) AS Total_Revenue
    FROM cust_detail cd
    JOIN cc_detail cc
        ON cd.Client_Num = cc.Client_Num
    GROUP BY
        cd.Customer_Job,
        cc.Client_Num
),
ranked_customers AS (
    SELECT
        Customer_Job,
        Client_Num,
        Total_Revenue,
        ROW_NUMBER() OVER (
            PARTITION BY Customer_Job
            ORDER BY Total_Revenue DESC
        ) AS Customer_Rank
    FROM customer_revenue
)
SELECT
    Customer_Job,
    Client_Num,
    Total_Revenue,
    Customer_Rank
FROM ranked_customers
WHERE Customer_Rank <= 3
ORDER BY Customer_Job, Customer_Rank;


/* ------------------------------------------------------------
   Q12. Card Category × Income Level

   Compare card categories across income levels.

   Income is stored as INT in the table, so the actual
   values from the database are used here.
*/

SELECT
    cc.Card_Category,
    cd.Income,
    COUNT(DISTINCT cc.Client_Num) AS Customers,
    SUM(cc.Total_Trans_Amt) AS Revenue,
    SUM(cc.Total_Trans_Ct) AS Transactions,
    ROUND(
        SUM(cc.Total_Trans_Amt) /
        COUNT(DISTINCT cc.Client_Num),
        2
    ) AS Revenue_Per_Customer
FROM cc_detail cc
JOIN cust_detail cd
    ON cc.Client_Num = cd.Client_Num
GROUP BY
    cc.Card_Category,
    cd.Income
ORDER BY Revenue DESC;


